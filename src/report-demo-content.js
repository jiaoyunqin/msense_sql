/* ===================== AI：轻量 Markdown 渲染 ===================== */
function inlineMD(s) {
  return esc(s).replace(/&lt;span class=&quot;note&quot;&gt;/g, '<span class="note">').replace(/&lt;\/span&gt;/g, '</span>').replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/\[\[cite:([\w-]*):([\w-]*):([^\]]+)\]\]/g, (m, sec, bid, label) => `<button class="cite" data-cite="${sec}:${bid}" title="跳转到报告原文">${ic('quote', 10)}${label}</button>`);
}
function renderMD(src) {
  const lines = src.split('\n'); let html = '', i = 0;
  while (i < lines.length) {
    const l = lines[i];
    if (/^\|/.test(l)) {
      const tb = []; while (i < lines.length && /^\|/.test(lines[i])) tb.push(lines[i++]);
      const rows = tb.filter((r, k) => k !== 1).map(r => r.replace(/^\||\|$/g, '').split('|'));
      html += `<div class="tw"><table><thead><tr>${rows[0].map(c => `<th>${inlineMD(c)}</th>`).join('')}</tr></thead><tbody>${rows.slice(1).map(r => `<tr>${r.map(c => `<td>${inlineMD(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;
      continue;
    }
    if (/^- /.test(l)) { let u = ''; while (i < lines.length && /^- /.test(lines[i])) u += `<li>${inlineMD(lines[i++].slice(2))}</li>`; html += `<ul>${u}</ul>`; continue; }
    if (/^\d+\. /.test(l)) { let u = ''; while (i < lines.length && /^\d+\. /.test(lines[i])) u += `<li>${inlineMD(lines[i++].replace(/^\d+\. /, ''))}</li>`; html += `<ol>${u}</ol>`; continue; }
    if (/^> /.test(l)) { html += `<blockquote>${inlineMD(l.slice(2))}</blockquote>`; i++; continue; }
    if (l.trim()) html += `<p>${inlineMD(l)}</p>`;
    i++;
  }
  return html;
}

