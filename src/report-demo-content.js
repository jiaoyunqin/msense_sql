function th(h) { return GLOSSARY[h.replace(/[?（(].*$/, '')] || GLOSSARY[h] ? `${esc(h)} <span title="${esc(GLOSSARY[h] || GLOSSARY[h.replace(/[?（(].*$/, '')])}" style="cursor:help;color:#a3a3a3">?</span>` : esc(h); }
function tableHTML(head, rows) {
  const two = head.groups;
  let h = '<table class="dt"><thead>';
  if (two) {
    h += `<tr><th class="lead" rowspan="2">${esc(head.cols[0])}</th>${head.cols.slice(1).map(c => `<th class="grp" colspan="${two.length}">${th(c)}</th>`).join('')}</tr>`;
    h += `<tr>${head.cols.slice(1).map(() => two.map((g, i) => `<th class="${i === 0 ? 'grp' : ''}">${esc(g)}</th>`).join('')).join('')}</tr>`;
  } else h += `<tr>${head.cols.map((c, i) => `<th class="${i === 0 ? 'lead' : ''}">${th(c)}</th>`).join('')}</tr>`;
  h += '</thead><tbody>';
  rows.forEach(r => { h += `<tr>${r.map((c, i) => `<td class="${i === 0 ? 'lead ' : ''}${c.cls || ''}">${c.html}</td>`).join('')}</tr>`; });
  return h + '</tbody></table>';
}
function transposedHTML(head, rows) {
  const cols = head.groups ? [head.cols[0]].concat(head.cols.slice(1).flatMap(c => head.groups.map(g => c + '·' + g))) : head.cols;
  let h = `<table class="dt"><thead><tr><th class="lead">指标</th>${rows.map(r => `<th>${r[0].html}</th>`).join('')}</tr></thead><tbody>`;
  for (let i = 1; i < cols.length; i++) h += `<tr><td class="lead">${esc(cols[i])}</td>${rows.map(r => `<td class="${r[i].cls || ''}">${r[i].html}</td>`).join('')}</tr>`;
  return h + '</tbody></table>';
}
