function flatSections(rep) {
  const out = [];
  rep.sections.forEach(s => { if (s.group) s.children.forEach(c => out.push(c)); else out.push(s); });
  return out;
}
function findSec(rep, id) {
  if (rep.summary && rep.summary.id === id) return { ...rep.summary, short: '实验核心结论' };
  return flatSections(rep).find(s => s.id === id);
}
